#!/usr/bin/env python3
"""Build hogman.network/docs: wrap each page in site/docs-src in the shared layout
(header, sidebar, footer) and write it to site/public/docs/.

    python3 site/docs-src/build.py

Edit the page fragments here, not the generated files. To add a page, add its
fragment and a line to PAGES."""
import os

SRC = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(SRC, "..", "public", "docs")

PAGES = [  # (file, nav title, page title, description)
    ("index", "Docs", "Hogman docs", "Guides, use cases and how Hogman works, in detail."),
    ("how-it-works", "How it works", "How Hogman works", "The parts of a pen, what happens on the wire, and what the keeper can and can't see."),
    ("join", "Joining a pen", "Joining a pen", "Getting your computer into a pen, adding more devices, side-by-side mode and leaving."),
    ("share", "Sharing a folder or site", "Sharing a folder or a website", "One command puts a folder, a port or a local site in your pen with its own name and HTTPS."),
    ("servers", "Running a server", "Running a server in your pen", "A dedicated server with Caddy or any ACME client, using the pen's certificate authority."),
    ("keeper", "Running your pen", "Running your pen", "Invites, the herd, suspend and the boot, names and roles, from the home page or the command line."),
    ("self-host", "Raising your own pen", "Raising your own pen", "Run Hogman on a server of your own: what you need and where the full guide is."),
    ("use-cases", "Use cases", "Use cases, worked through", "Families, clubs, small companies, customer portals and side projects, set up step by step."),
    ("faq", "FAQ and troubleshooting", "FAQ and troubleshooting", "Common questions, and fixes for the problems people actually hit."),
]

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · Hogman</title>
<meta name="description" content="{desc}">
<meta name="theme-color" content="#0e080c">
<link rel="icon" href="/favicon.svg?v=metal5" type="image/svg+xml">
<link rel="stylesheet" href="/styles.css?v=metal8">
</head>
<!-- Generated by site/docs-src/build.py from site/docs-src. Edit there. -->
<body class="docs-page">
<header class="top">
  <a class="brand" href="/" aria-label="Hogman home">H&Ouml;GMAN</a>
  <nav>
    <a href="/">Home</a>
    <a href="/docs/">Docs</a>
    <a href="/docs/how-it-works.html">How it works</a>
    <a href="https://get.hogman.network/">Get a pen</a>
    <a href="https://github.com/celtiberi/hogman">Source</a>
  </nav>
</header>
<div class="studs" aria-hidden="true"></div>
<div class="docs">
<aside class="docs-nav" aria-label="Docs pages">
<p class="docs-nav-h">Docs</p>
<ul>
{nav}
</ul>
</aside>
<main class="docs-main">
"""

FOOT = """
<p class="docs-edit fine">Something wrong or unclear on this page? Its source is in
  <a href="https://github.com/celtiberi/hogman/tree/main/site/docs-src">site/docs-src</a>; issues and fixes welcome.</p>
</main>
</div>
<footer>
  <p>Keep a clean pen.</p>
  <p class="fine">Hogman is open source (AGPL) and not audited yet.</p>
</footer>
</body>
</html>
"""

os.makedirs(OUT, exist_ok=True)
for f, navt, title, desc in PAGES:
    body = open(os.path.join(SRC, f + ".html")).read()
    nav = "\n".join(
        '<li><a href="/docs/{}"{}>{}</a></li>'.format(
            "" if g == "index" else g + ".html",
            ' aria-current="page"' if g == f else "",
            n,
        )
        for g, n, _, _ in PAGES
    )
    html = HEAD.format(title=title, desc=desc, nav=nav) + body.strip() + "\n" + FOOT
    open(os.path.join(OUT, f + ".html"), "w").write(html)
    print("wrote", f)
